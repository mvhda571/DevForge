import { Router } from 'express';
import * as c from '../controllers/adminController.js';
import { requireAuth, requireRole } from '../middleware/auth.js';
import { validate } from '../middleware/validate.js';
import { idParam } from '../validation/common.js';
import { careerSchema, lessonUpdateSchema, questionSchema, quizUpdateSchema, universitySchema, userUpdateSchema } from '../validation/admin.js';

const r = Router();
r.use(requireAuth, requireRole('admin'));
r.get('/stats', c.stats);
r.get('/users', c.users);
r.patch('/users/:id', validate({ params: idParam, body: userUpdateSchema }), c.updateUser);
r.delete('/users/:id', validate({ params: idParam }), c.deleteUser);
r.get('/careers', c.careers);
r.post('/careers', validate({ body: careerSchema }), c.createCareer);
r.put('/careers/:id', validate({ params: idParam, body: careerSchema.partial() }), c.updateCareer);
r.delete('/careers/:id', validate({ params: idParam }), c.deleteCareer);
r.get('/questions', c.questions);
r.patch('/questions/:id', validate({ params: idParam, body: questionSchema }), c.updateQuestion);
r.get('/lessons', c.lessons);
r.get('/lessons/:id', validate({ params: idParam }), c.lesson);
r.patch('/lessons/:id', validate({ params: idParam, body: lessonUpdateSchema }), c.updateLesson);
r.put('/lessons/:id/quiz', validate({ params: idParam, body: quizUpdateSchema }), c.updateQuiz);
r.get('/universities', c.universities);
r.post('/universities', validate({ body: universitySchema }), c.createUniversity);
r.put('/universities/:id', validate({ params: idParam, body: universitySchema.partial() }), c.updateUniversity);
r.delete('/universities/:id', validate({ params: idParam }), c.deleteUniversity);
r.get('/content-check', c.contentCheck);
r.get('/audit-logs', c.auditLogs);
export default r;
